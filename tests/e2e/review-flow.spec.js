import {test,expect} from '@playwright/test';
import {preparePageScreenshot} from './helpers.js';
const data = page => page.evaluate(() => {const w=JSON.parse(localStorage.getItem('se-tailoring-workspace-v1'));return w.assessments.find(a=>a.id===w.activeId).data;});

test('partial review records exactly one adjustment, retains another draft, and offers a truthful report after reload',async({page},testInfo)=>{
 await page.goto('./');
 await expect(page.getByRole('heading',{name:'Your assessments',exact:true})).toHaveCount(0);
 await page.locator('#btn-start-assessment').click();
 await page.getByLabel('Project code',{exact:true}).fill('SYNTHETIC-REVIEW-FLOW');
 await page.getByRole('button',{name:'Next: Complexity →',exact:true}).click();
 await page.getByRole('radio',{name:/^M1 score 3:/}).check();
 await page.getByRole('button',{name:'Go to Results step',exact:true}).click();
 await expect(page.locator('.spiderweb-chart')).toBeVisible();
 await expect(page.getByRole('heading',{name:'Review status',exact:true})).toHaveCount(0);
 await expect(page.locator('.result-card')).toHaveCount(22);
 const form9=page.locator('form[data-process-review="9"]'),form10=page.locator('form[data-process-review="10"]');
 await form9.locator('..').locator('summary').click();
 await form9.getByRole('combobox',{name:'Decision for Project Planning',exact:true}).selectOption('adjust');
 await form9.getByRole('combobox',{name:'Chosen level for Project Planning',exact:true}).selectOption('comprehensive');
 await form9.getByRole('textbox').fill('Additional coordination for the synthetic interfaces');
 await form10.locator('..').locator('summary').click();
 await form10.getByRole('combobox',{name:'Decision for Project Assessment & Control',exact:true}).selectOption('keep');
 await form10.getByRole('textbox').fill('Unsubmitted draft rationale');
 await form9.getByRole('button',{name:'Record decision for Project Planning',exact:true}).click();
 let node=(await data(page)).assessmentTree.nodes.default;
 expect(Object.keys(node.decisionRecords)).toEqual(['9']);
 expect(node.decisionHistory).toHaveLength(1);
 expect(node.decisionDrafts[10].justification).toBe('Unsubmitted draft rationale');
 await page.getByRole('button',{name:'View report',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Draft Tailoring Report',exact:true})).toBeVisible();
 await expect(page.locator('#btn-export-html')).toBeDisabled();
 await expect(page.locator('.report-process-plan')).toContainText('Framework: Standard');
 await expect(page.locator('.report-process-plan')).toContainText('Recorded human adjustment');
 await expect(page.locator('.report-process-plan')).toContainText('Additional coordination');
 await expect(page.locator('.report-process-plan')).toContainText('Unsaved decision draft');
 await preparePageScreenshot(page);
 await page.screenshot({path:testInfo.outputPath('draft-report-with-human-adjustment.png'),fullPage:false});
 await page.reload();
 await page.getByRole('button',{name:'Restore',exact:true}).click();
 await expect(page.locator('#autosave-restore-overlay')).toHaveCount(0);
 await expect(page).toHaveURL(/#dashboard$/);
 await expect(page.locator('#main-content')).not.toHaveAttribute('inert','');
 await page.getByRole('button',{name:'Report',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Draft Tailoring Report',exact:true})).toBeVisible();
 await expect(page.locator('.report-process-plan')).toContainText('Additional coordination');
 node=(await data(page)).assessmentTree.nodes.default;
 expect(node.decisionHistory).toHaveLength(1);
 expect(node.decisionDrafts[10].justification).toBe('Unsubmitted draft rationale');
 await page.setViewportSize({width:390,height:844});
 await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByRole('button',{name:'Review / adjust decisions',exact:true}).click();
 await expect(page.getByRole('heading',{name:'Tailoring decisions',exact:true})).toBeVisible();
 const reasonBounds=await page.locator('#decision-reason-9').boundingBox();
 expect(reasonBounds.x).toBeGreaterThanOrEqual(0);
 expect(reasonBounds.x+reasonBounds.width).toBeLessThanOrEqual(390);
 await page.locator('#btn-view-report').click();
 await expect(page.getByRole('heading',{name:'Draft Tailoring Report',exact:true})).toBeVisible();
});


test('inline review preserves an imported current choice and rationale before recording it',async({page})=>{
 const {runFullAssessment}=await import('../../src/utils/assessment-engine.js');
 const {buildExportConfig}=await import('../../src/utils/export-import.js');
 const {captureRecommendation}=await import('../../src/utils/tailoring-decisions.js');
 const scores=Object.fromEntries(Array.from({length:16},(_,i)=>[`M${i+1}`,3]));
 const metricAssessments=Object.fromEntries(Object.entries(scores).map(([id,score])=>[id,{score,status:'assessed',definitionVersion:3,qualifiers:[],rationale:'Synthetic legacy check',evidenceRefs:[]}]));
 const result=runFullAssessment(scores,undefined,{metricAssessments});
 const node={id:'default',name:'Synthetic imported system',parentId:null,childIds:[],scores,metricAssessments,levels:result.levels,assessmentResult:result,manualAdjustments:{9:{level:'comprehensive',justification:'Preserve imported coordination rationale'}}};
 captureRecommendation(node,result);
 const config=buildExportConfig({...result,scores,metricAssessments,projectInfo:{name:'IMPORTED-CHOICE'},manualAdjustments:node.manualAdjustments,assessmentTree:{rootId:'default',activeId:'default',nodes:{default:node}}},{mode:'identified'});
 await page.goto('./');
 await page.getByRole('button',{name:'Session actions',exact:true}).click();
 const chooser=page.waitForEvent('filechooser');
 await page.locator('#btn-import').click();
 await (await chooser).setFiles({name:'synthetic-imported-choice.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(config))});
 await expect(page.getByText('Configuration imported successfully!')).toBeVisible();
 await page.goto('./#review');
 const form=page.locator('form[data-process-review="9"]');
 await form.locator('..').locator('summary').click();
 await expect(form.getByRole('combobox',{name:'Chosen level for Project Planning',exact:true})).toHaveValue('comprehensive');
 await expect(form.getByRole('textbox')).toHaveValue('Preserve imported coordination rationale');
 await form.getByRole('button',{name:'Record decision for Project Planning',exact:true}).click();
 const saved=(await data(page)).assessmentTree.nodes.default;
 expect(saved.manualAdjustments[9].level).toBe('comprehensive');
 expect(saved.decisionRecords[9].justification).toBe('Preserve imported coordination rationale');
 expect(saved.decisionHistory).toHaveLength(1);
});
